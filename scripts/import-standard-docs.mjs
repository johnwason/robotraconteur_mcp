// Copy the standard service definition documentation into src/standard_docs.ts, for
// robotraconteur_help. The standard robdefs carry few docstrings, to keep them small on the wire, so
// their documentation is served from here instead. Run it again when the standard docs change:
//
//     node scripts/import-standard-docs.mjs <path to a robotraconteur_standard_robdef checkout>
//
// The pages are copied as written, from docs/group1, one per service, named by the file name.

import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = process.argv[2];
if (!repo) throw new Error("Give the path to a robotraconteur_standard_robdef checkout");
const commit = execFileSync("git", ["-C", repo, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const dirty = execFileSync("git", ["-C", repo, "status", "--porcelain", "docs/group1"], { encoding: "utf8" }).trim();
if (dirty) throw new Error(`docs/group1 has uncommitted changes, so the commit would not say what was copied:\n${dirty}`);

const dir = join(repo, "docs", "group1");
const pages = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".md")).sort())
{
    const name = basename(file, ".md");
    const page = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
    // The first paragraph after the title, cut to its first sentence, for the list of services
    const first = page.split("\n\n").find((p, i) => i > 0 && !p.startsWith("#")) ?? "";
    const sentence = first.replace(/\s+/g, " ").replace(/`/g, "").split(/(?<=\.)\s/)[0];
    pages[name] = { summary: sentence, page };
}

const out = `// Generated by scripts/import-standard-docs.mjs from robotraconteur_standard_robdef docs/group1 at
// commit ${commit}. Do not edit; run the script again instead.
// The documentation is from the robotraconteur_standard_robdef repository, under the Apache License,
// Version 2.0, as this package is.

/** The robotraconteur_standard_robdef commit the pages were copied from */
export const STANDARD_DOCS_COMMIT = "${commit}";

/** The documentation page of each standard service definition, by service name, with a one-line summary */
export const STANDARD_DOCS: Record<string, { summary: string; page: string }> = ${JSON.stringify(pages, null, 4)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "standard_docs.ts");
writeFileSync(target, out);
console.log(`Wrote ${Object.keys(pages).length} pages from ${commit} to ${target}`);
